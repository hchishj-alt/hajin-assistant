export function legalView(view, kind) {
  const d = DOCS[kind] || DOCS.terms;
  view.innerHTML = `<div class="top"><a class="iconbtn" href="#/hello" aria-label="뒤로">${ic('left', 22)}</a><h1 class="h1s">${d[0]}</h1><span style="width:44px"></span></div>
    <p class="tip c onlyfx">이 문서는 한국어 원문이 기준이에요.</p>
    <article class="doc noi18n">${d[1]()}</article>
    ${legalLinks()}${bizLine()}`;
  view.querySelector('.top a').onclick = e => { if (history.length > 1) { e.preventDefault(); history.back(); } };
}
